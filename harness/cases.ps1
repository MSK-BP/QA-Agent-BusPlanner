<#
.SYNOPSIS
  Lists, checks and reports on the markdown test cases of the active tenant.

.DESCRIPTION
  Layout (all under <tenant>/tests/, see templates/tenant/tests/README.md):
    <module>/<flow>/<ID>.md     one case per file, front matter + Steps + Expected
    suites/<name>.md            a named suite: filters and/or an explicit case list
    runs/<run-id>/RUN.md        one run: the case list and the run report
    runs/<run-id>/<ID>.md       one result per case
    MATRIX.md, cases.csv        generated by -Action matrix
  Evidence (screenshots, network logs) goes to the tenant's run folder, outside git:
    <RunRoot>/runs/<run-id>/

  -Action list      Cases that match the filters (default). Retired cases only with -Status retired.
  -Action validate  Checks every case file. Exit code 1 if any error.
  -Action new-run   Creates a run folder for the selected cases and prints it. Only
                    approved cases, unless -Rehearsal (then draft and reviewed too).
  -Action matrix    Writes tests/MATRIX.md and tests/cases.csv from the cases and
                    the latest result of each.

  Filters take comma-separated values: -Module ride-support -Priority P1,P2.

.EXAMPLE
  .\harness\cases.ps1 -Action validate
  .\harness\cases.ps1 -Module ride-support -Flow F2 -Priority P1
  .\harness\cases.ps1 -Action new-run -Suite smoke -Env us-staging -Json
  .\harness\cases.ps1 -Action matrix
#>
param(
    [ValidateSet('list', 'validate', 'new-run', 'matrix')] [string] $Action = 'list',
    [string] $Suite,
    [string] $Module,
    [string] $Flow,
    [string] $Priority,
    [string] $Tag,
    [string] $Ticket,
    [string] $Status,
    [string[]] $Id,
    [string] $Env,
    [switch] $Rehearsal,
    [switch] $Json
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'tenant.ps1')
$tenant = Get-QaTenant
if (-not $tenant) { throw 'No active tenant. Run harness\use-tenant.ps1 <name> first.' }
$tests = Join-Path $tenant.Root 'tests'
$utf8 = New-Object Text.UTF8Encoding $false
$listFields = 'channels', 'roles', 'spec', 'data', 'tags'
$statuses = 'draft', 'reviewed', 'approved', 'retired'
$channelsAllowed = 'ui', 'api', 'sql', 'device', 'cli'

function Read-FrontMatter([string] $path) {
    $lines = [IO.File]::ReadAllLines($path, [Text.Encoding]::UTF8)
    if ($lines.Count -lt 2 -or $lines[0].Trim() -ne '---') { return $null }
    $fm = [ordered]@{}
    $end = -1
    for ($i = 1; $i -lt $lines.Count; $i++) {
        if ($lines[$i].Trim() -eq '---') { $end = $i; break }
        $l = $lines[$i] -replace '\s+#\s.*$', ''
        if ($l -match '^\s*([A-Za-z][\w-]*)\s*:\s*(.*)$') {
            $k = $matches[1].ToLower(); $v = $matches[2].Trim()
            if ($v -match '^\[(.*)\]$') {
                $v = @($matches[1].Split(',') | ForEach-Object { $_.Trim().Trim('"', "'") } | Where-Object { $_ })
            } else { $v = $v.Trim('"', "'") }
            $fm[$k] = $v
        }
    }
    if ($end -lt 0) { return $null }
    $body = if ($end + 1 -lt $lines.Count) { $lines[($end + 1)..($lines.Count - 1)] } else { @() }
    [pscustomobject]@{ Fields = $fm; Body = @($body) }
}

function Get-Field($fm, [string] $name) {
    if (-not $fm.Contains($name)) { if ($listFields -contains $name) { return @() } else { return '' } }
    $v = $fm[$name]
    if ($listFields -contains $name) { return @($v | Where-Object { $_ }) }
    [string]$v
}

function Get-Cases {
    if (-not (Test-Path $tests)) { return @() }
    $skip = @((Join-Path $tests 'suites'), (Join-Path $tests 'runs'))
    Get-ChildItem $tests -Recurse -File -Filter *.md | Where-Object {
        $p = $_.FullName
        ($_.DirectoryName -ne $tests) -and -not ($skip | Where-Object { $p.StartsWith($_ + '\') -or $p.StartsWith($_ + '/') })
    } | ForEach-Object {
        $doc = Read-FrontMatter $_.FullName
        $rel = $_.FullName.Substring($tenant.Root.Length + 1) -replace '\\', '/'
        if (-not $doc) { return [pscustomobject]@{ Id = $_.BaseName; Path = $rel; File = $_.FullName; Broken = $true } }
        $f = $doc.Fields
        $expected = @($doc.Body | ForEach-Object {
            if ($_ -match '^\s*-\s*(E\d+)\s*\(([^)]*)\)\s*:') {
                $parts = $matches[2].Split(',') | ForEach-Object { $_.Trim() }
                [pscustomobject]@{ Id = $matches[1]; Channel = ($parts | Where-Object { $channelsAllowed -contains $_ } | Select-Object -First 1); Raw = $_.Trim() }
            }
        })
        [pscustomobject]@{
            Id = Get-Field $f 'id'; Title = Get-Field $f 'title'; Module = Get-Field $f 'module'; Flow = Get-Field $f 'flow'
            Priority = Get-Field $f 'priority'; Status = Get-Field $f 'status'; Env = Get-Field $f 'env'; Ticket = Get-Field $f 'ticket'
            Channels = Get-Field $f 'channels'; Roles = Get-Field $f 'roles'; Tags = Get-Field $f 'tags'; Spec = Get-Field $f 'spec'
            ConvertLater = Get-Field $f 'convert-later'; ApprovedBy = Get-Field $f 'approved-by'
            Fields = $f; Body = $doc.Body; Expected = $expected; Path = $rel; File = $_.FullName; FileId = $_.BaseName; Broken = $false
        }
    }
}

function Test-Match($value, [string] $filter) {
    if (-not $filter) { return $true }
    $want = $filter.Split(',') | ForEach-Object { $_.Trim().ToLower() } | Where-Object { $_ }
    $have = @($value) | ForEach-Object { ([string]$_).ToLower() }
    [bool]($have | Where-Object { $want -contains $_ })
}

function Select-Cases($cases, [hashtable] $filters, [string[]] $ids, [string] $statusFilter) {
    $anyFilter = [bool]($filters.Values | Where-Object { $_ })
    @($cases | Where-Object { -not $_.Broken } | Where-Object {
        $c = $_
        $byId = $ids -and ($ids | Where-Object { $_ -ieq $c.Id })
        $byFilter = $anyFilter -and (Test-Match $c.Module $filters.Module) -and (Test-Match $c.Flow $filters.Flow) -and
            (Test-Match $c.Priority $filters.Priority) -and (Test-Match $c.Tags $filters.Tag) -and (Test-Match $c.Ticket $filters.Ticket)
        $all = -not $anyFilter -and -not $ids
        ($byId -or $byFilter -or $all) -and (Test-Match $c.Status $statusFilter)
    })
}

function Resolve-Selection {
    $filters = @{ Module = $Module; Flow = $Flow; Priority = $Priority; Tag = $Tag; Ticket = $Ticket }
    $ids = @($Id | Where-Object { $_ } | ForEach-Object { $_.Split(',') } | ForEach-Object { $_.Trim() } | Where-Object { $_ })
    $script:suiteEnv = ''
    if ($Suite) {
        $sf = Join-Path $tests "suites\$Suite.md"
        if (-not (Test-Path $sf)) { throw "No suite file tests/suites/$Suite.md." }
        $s = (Read-FrontMatter $sf).Fields
        foreach ($k in 'module', 'flow', 'priority', 'tag', 'ticket') {
            if ($s.Contains($k) -and -not $filters[$k]) { $filters[$k] = (@($s[$k]) -join ',') }
        }
        if ($s.Contains('cases')) { $ids += @($s['cases']) }
        if ($s.Contains('env')) { $script:suiteEnv = [string]$s['env'] }
    }
    @{ Filters = $filters; Ids = $ids }
}

function Get-LatestResults {
    $map = @{}
    $runs = Join-Path $tests 'runs'
    if (-not (Test-Path $runs)) { return $map }
    foreach ($dir in (Get-ChildItem $runs -Directory | Sort-Object Name)) {
        foreach ($f in (Get-ChildItem $dir.FullName -File -Filter *.md | Where-Object { $_.Name -ne 'RUN.md' })) {
            $doc = Read-FrontMatter $f.FullName
            if (-not $doc) { continue }
            $v = Get-Field $doc.Fields 'verdict'
            if (-not $v) { continue }
            $map[$f.BaseName.ToLower()] = [pscustomobject]@{
                Verdict = $v; Env = Get-Field $doc.Fields 'env'; Build = Get-Field $doc.Fields 'build'
                Run = $dir.Name; Rehearsal = (Get-Field $doc.Fields 'rehearsal'); Link = "runs/$($dir.Name)/$($f.Name)"
            }
        }
    }
    $map
}

$cases = @(Get-Cases)

switch ($Action) {
    'validate' {
        $errors = New-Object Collections.Generic.List[string]
        $warnings = New-Object Collections.Generic.List[string]
        $seen = @{}
        foreach ($c in $cases) {
            $where = $c.Path
            if ($c.Broken) { $errors.Add("${where}: no front matter between --- lines"); continue }
            foreach ($req in 'id', 'title', 'module', 'priority', 'status', 'channels', 'env') {
                $v = Get-Field $c.Fields $req
                if (-not $v -or @($v).Count -eq 0) { $errors.Add("${where}: missing '$req'") }
            }
            if ($c.Id -and $c.Id -ne $c.FileId) { $errors.Add("${where}: id '$($c.Id)' does not match the file name") }
            if ($c.Id) {
                $k = $c.Id.ToLower()
                if ($seen.ContainsKey($k)) { $errors.Add("${where}: duplicate id, also in $($seen[$k])") } else { $seen[$k] = $where }
            }
            if ($c.Status -and $statuses -notcontains $c.Status) { $errors.Add("${where}: status '$($c.Status)' is not one of $($statuses -join ', ')") }
            if ($c.Priority -and $c.Priority -notmatch '^P[1-3]$') { $errors.Add("${where}: priority must be P1, P2 or P3") }
            foreach ($ch in $c.Channels) { if ($channelsAllowed -notcontains $ch) { $errors.Add("${where}: channel '$ch' is not one of $($channelsAllowed -join ', ')") } }
            if ($c.Status -eq 'approved' -and -not $c.ApprovedBy) { $errors.Add("${where}: approved without 'approved-by'") }
            $text = $c.Body -join "`n"
            if ($text -notmatch '(?m)^##\s+Steps') { $errors.Add("${where}: no '## Steps' section") }
            if ($text -notmatch '(?m)^##\s+Expected') { $errors.Add("${where}: no '## Expected' section") }
            if (-not $c.Expected) { $errors.Add("${where}: no expected lines like '- E1 (step 2, ui): ...'") }
            $eids = @{}
            foreach ($e in $c.Expected) {
                if ($eids.ContainsKey($e.Id)) { $errors.Add("${where}: $($e.Id) appears twice") } else { $eids[$e.Id] = 1 }
                if (-not $e.Channel) { $errors.Add("${where}: $($e.Id) names no channel ($($channelsAllowed -join ', '))") }
                elseif ($c.Channels -notcontains $e.Channel) { $errors.Add("${where}: $($e.Id) uses channel '$($e.Channel)', not listed in channels") }
            }
            if ($text -notmatch '(?m)^##\s+Clean-up') { $warnings.Add("${where}: no '## Clean-up' section (write 'None' if the case creates no data)") }
            if ($c.Channels -contains 'ui' -and -not $c.Roles) { $warnings.Add("${where}: ui case without 'roles'") }
        }
        "Cases checked: $(@($cases).Count). Errors: $($errors.Count). Warnings: $($warnings.Count)."
        $errors | ForEach-Object { "ERROR   $_" }
        $warnings | ForEach-Object { "WARNING $_" }
        if ($errors.Count) { exit 1 }
    }

    'list' {
        $sel = Resolve-Selection
        $statusFilter = if ($Status) { $Status } else { 'draft,reviewed,approved' }
        $picked = @(Select-Cases $cases $sel.Filters $sel.Ids $statusFilter)
        if ($Json) { $picked | Select-Object Id, Title, Module, Flow, Priority, Status, Env, Ticket, Channels, Roles, Tags, Path | ConvertTo-Json -Depth 4; return }
        $picked | Sort-Object Module, Flow, Id | Format-Table Id, Priority, Status, @{ n = 'Channels'; e = { $_.Channels -join ',' } }, Title, Path -AutoSize | Out-String -Width 220
        "$($picked.Count) case(s)."
    }

    'new-run' {
        $sel = Resolve-Selection
        $runEnv = if ($Env) { $Env } elseif ($suiteEnv) { $suiteEnv } else { throw 'Give -Env (an environment allowed in knowledge/environments.md).' }
        $statusFilter = if ($Rehearsal) { 'draft,reviewed,approved' } else { 'approved' }
        $picked = @(Select-Cases $cases $sel.Filters $sel.Ids $statusFilter | Sort-Object Priority, Module, Flow, Id)
        if (-not $picked) { throw "No $statusFilter cases match. Approved cases only, unless -Rehearsal." }
        $label = if ($Suite) { $Suite } elseif ($Module) { $Module } elseif ($Ticket) { $Ticket } else { 'adhoc' }
        $label = ($label -replace '[^\w-]', '-').ToLower()
        $runId = "$(Get-Date -Format 'yyyy-MM-dd-HHmm')-$label-$($runEnv.ToLower())"
        $runDir = Join-Path $tests "runs\$runId"
        $evidence = Join-Path $tenant.RunRoot "runs\$runId"
        New-Item -ItemType Directory -Force $runDir, $evidence | Out-Null
        $rows = $picked | ForEach-Object { "| [$($_.Id)](../../$($_.Path -replace '^tests/', '')) | $($_.Priority) | $($_.Status) | $($_.Channels -join ', ') | $($_.Roles -join ', ') | $($_.Title) | [result]($($_.Id).md) | |" }
        $parts = @('module', 'flow', 'priority', 'tag', 'ticket' | ForEach-Object { if ($sel.Filters[$_]) { "$_=$($sel.Filters[$_])" } }) + @($sel.Ids | ForEach-Object { "id=$_" })
        $selection = if ($Suite) { "suite $Suite" } else { $parts -join ' ' }
        $mode = if ($Rehearsal) { 'Rehearsal: unapproved cases included. These results do not count for a sign-off.' } else { 'Approved cases only.' }
        $run = @"
---
run: $runId
env: $runEnv
build:
started: $(Get-Date -Format 'yyyy-MM-dd HH:mm')
rehearsal: $(if ($Rehearsal) { 'yes' } else { 'no' })
selection: $selection
verdict:
---
# Run $runId

$mode Evidence (screenshots, network logs) is outside git, in ``$evidence``.

## Verdict

(Filled in at the end of the run.)

## Cases

| Case | P | Status | Channels | Roles | Title | Result | Verdict |
|---|---|---|---|---|---|---|---|
$($rows -join "`n")

## Failures and triage

## Bugs drafted (not filed)

## Not run, and why
"@
        [IO.File]::WriteAllText((Join-Path $runDir 'RUN.md'), $run.Replace("`r`n", "`n"), $utf8)
        $out = [pscustomobject]@{
            RunId = $runId
            RunFolder = ($runDir.Substring($tenant.Root.Length + 1) -replace '\\', '/')
            Evidence = $evidence
            Env = $runEnv
            Rehearsal = [bool]$Rehearsal
            Sequential = @($picked | Where-Object { $_.Channels -contains 'ui' -or $_.Channels -contains 'device' -or $_.Channels -contains 'cli' } | ForEach-Object { $_.Path })
            Parallel = @($picked | Where-Object { -not ($_.Channels -contains 'ui' -or $_.Channels -contains 'device' -or $_.Channels -contains 'cli') } | ForEach-Object { $_.Path })
        }
        if ($Json) { $out | ConvertTo-Json -Depth 4 } else { $out | Format-List | Out-String -Width 220 }
    }

    'matrix' {
        $latest = Get-LatestResults
        $live = @($cases | Where-Object { -not $_.Broken -and $_.Status -ne 'retired' } | Sort-Object Module, Flow, Id)
        $count = @{}
        $rows = foreach ($c in $live) {
            $r = $latest[$c.Id.ToLower()]
            $v = if ($r) { $r.Verdict + $(if ($r.Rehearsal -eq 'yes') { ' (rehearsal)' } else { '' }) } else { 'Not run' }
            $key = if ($r) { $r.Verdict } else { 'Not run' }
            $count[$key] = 1 + [int]$count[$key]
            $link = if ($r) { "[$($r.Run)]($($r.Link))" } else { '' }
            "| [$($c.Id)]($($c.Path -replace '^tests/', '')) | $($c.Module) | $($c.Flow) | $($c.Priority) | $($c.Status) | $v | $(if ($r) { $r.Env }) | $(if ($r) { $r.Build }) | $link | $($c.Title) |"
        }
        $summary = ($count.GetEnumerator() | Sort-Object Name | ForEach-Object { "$($_.Name): $($_.Value)" }) -join '; '
        $md = @"
# Coverage matrix

Generated by ``harness/cases.ps1 -Action matrix`` on $(Get-Date -Format 'yyyy-MM-dd HH:mm'). Do not edit by hand.

Cases: $($live.Count). $summary

| Case | Module | Flow | P | Status | Last verdict | Env | Build | Run | Title |
|---|---|---|---|---|---|---|---|---|---|
$($rows -join "`n")
"@
        New-Item -ItemType Directory -Force $tests | Out-Null
        [IO.File]::WriteAllText((Join-Path $tests 'MATRIX.md'), $md.Replace("`r`n", "`n"), $utf8)
        $csv = $live | ForEach-Object {
            $r = $latest[$_.Id.ToLower()]
            [pscustomobject]@{
                id = $_.Id; title = $_.Title; module = $_.Module; flow = $_.Flow; priority = $_.Priority; status = $_.Status
                ticket = $_.Ticket; spec = ($_.Spec -join ';'); channels = ($_.Channels -join ';'); roles = ($_.Roles -join ';')
                tags = ($_.Tags -join ';'); env = $_.Env; convert_later = $_.ConvertLater
                expected = (($_.Expected | ForEach-Object { $_.Raw -replace '^-\s*', '' }) -join ' | ')
                last_verdict = $(if ($r) { $r.Verdict } else { 'Not run' }); last_run = $(if ($r) { $r.Run } else { '' })
            }
        }
        $csvText = if ($csv) { ($csv | ConvertTo-Csv -NoTypeInformation) -join "`n" } else { '' }
        [IO.File]::WriteAllText((Join-Path $tests 'cases.csv'), $csvText, $utf8)
        "Wrote tests/MATRIX.md and tests/cases.csv: $($live.Count) case(s). $summary"
    }
}
